const NU_STORAGE_KEY = 'med_nu_dri_tracking_records_v1';

export function getStoredNuDisbursements(): NuDisbursementRecord[] {
  try {
    const raw = localStorage.getItem(NU_STORAGE_KEY);
    if (!raw) return INITIAL_NU_DISBURSEMENTS;
    const parsed = JSON.parse(raw);
    return Array.isArray(parsed) && parsed.length > 0 ? parsed : INITIAL_NU_DISBURSEMENTS;
  } catch (e) {
    console.error('Failed to load NU disbursements from storage', e);
    return INITIAL_NU_DISBURSEMENTS;
  }
}

export function saveStoredNuDisbursements(records: NuDisbursementRecord[]): void {
  try {
    localStorage.setItem(NU_STORAGE_KEY, JSON.stringify(records));
  } catch (e) {
    console.error('Failed to save NU disbursements to storage', e);
  }
}

export function upsertNuDisbursement(
  records: NuDisbursementRecord[],
  updated: NuDisbursementRecord
): NuDisbursementRecord[] {
  const idx = records.findIndex(r => r.id === updated.id);
  let next: NuDisbursementRecord[];
  if (idx >= 0) {
    next = [...records];
    next[idx] = { ...updated, updatedAt: new Date().toISOString().split('T')[0] };
  } else {
    next = [
      {
        ...updated,
        id: updated.id || ('nu-rec-' + Date.now() + '-' + Math.random().toString(36).substring(2, 6)),
        createdAt: updated.createdAt || new Date().toISOString().split('T')[0],
        updatedAt: new Date().toISOString().split('T')[0]
      },
      ...records
    ];
  }
  saveStoredNuDisbursements(next);
  return next;
}
