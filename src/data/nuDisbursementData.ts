const STORAGE_KEY = 'med_nu_disbursement_records_v1';

export function getStoredNuDisbursements(): NuDisbursementRecord[] {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (e) {
    console.error('Failed to load stored NU disbursements:', e);
  }
  return INITIAL_NU_DISBURSEMENTS;
}

export function saveStoredNuDisbursements(records: NuDisbursementRecord[]): void {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(records));
  } catch (e) {
    console.error('Failed to save NU disbursements:', e);
  }
}

export function upsertNuDisbursement(
  currentRecords: NuDisbursementRecord[],
  record: NuDisbursementRecord
): NuDisbursementRecord[] {
  const idx = currentRecords.findIndex(r => r.id === record.id);
  let updated: NuDisbursementRecord[];
  if (idx >= 0) {
    updated = [...currentRecords];
    updated[idx] = { ...record, updatedAt: new Date().toISOString().split('T')[0] };
  } else {
    updated = [{ ...record, updatedAt: new Date().toISOString().split('T')[0] }, ...currentRecords];
  }
  saveStoredNuDisbursements(updated);
  return updated;
}
